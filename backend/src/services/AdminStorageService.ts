import { prisma } from '../lib/prisma';
import { storage } from '../lib/storage';

/**
 * Map of MinIO storage (admin > Storage): walks the bucket and aggregates objects by key convention
 * (see StorageService and the FFmpeg worker) to answer "where does each file type live?". The
 * classification and aggregation functions are pure (and tested); only `storageReport` touches
 * MinIO/DB.
 */

/** Root category of an object key (first segment of the path). */
export type StorageCategory =
  | 'originals' // projects/{slug}/… — uploaded files (source of truth)
  | 'derived' // derived/{mediaId}/… — derivatives generated by the workers
  | 'studio' // studio/hdris|ocio — studio libraries
  | 'avatars' // avatars/{userId}.…
  | 'branding' // branding/logo-*.…
  | 'documents' // documents/… — PDFs of the Documents page
  | 'comments' // comments/attachments/{userId}/… — attachments and voice notes
  | 'quarantine' // quarantine/{mediaId}/… — infected uploads isolated (ClamAV)
  | 'other';

export interface StorageObjectInfo {
  key: string;
  size: number;
}

export interface StorageAgg {
  count: number;
  bytes: number;
}

export interface StorageReportData {
  totalObjects: number;
  totalBytes: number;
  /** Aggregate per root category. */
  categories: Record<string, StorageAgg>;
  /** Derivative details (`derived/{id}/…`) per file subtype. */
  derived: Record<string, StorageAgg>;
  /** Studio library details (hdris / ocio). */
  studio: Record<string, StorageAgg>;
  /** Usage of originals per project slug (`projects/{slug}/…`). */
  projects: { slug: string; objects: number; bytes: number }[];
}

/** Subtype of a derivative (`derived/{mediaId}/<rest>`), derived from the file name. */
export function derivedSubtype(rest: string): string {
  if (rest.startsWith('hls/')) return 'hls';
  if (rest.startsWith('thumbnail.')) return 'thumbnails';
  if (rest === 'model.glb') return 'glb';
  // `proxy-trim.mp4`: trimming was removed (Phase 50, batch 4), but this mapping classifies existing
  // objects, it does not produce them. Removing it would move historical derivatives from `proxies` to
  // `other` on the storage dashboard.
  if (rest === 'proxy.mp4' || rest === 'proxy-trim.mp4') return 'proxies';
  if (rest === 'client.mp4') return 'client';
  if (rest === 'timeline-sprite.jpg') return 'sprites';
  // `reference-{uuid}.{ext}` (Phase 24, multi) + legacy `reference.png` (single reference).
  if (rest.startsWith('reference')) return 'references';
  if (rest === 'splat-mask.bin' || rest === 'splat-subset.bin') return 'splat-edits';
  return 'other';
}

/** Classifies a MinIO object key according to the application's conventions. */
export function classifyKey(key: string): {
  category: StorageCategory;
  /** Subtype (derivatives: hls/thumbnails/...; studio: hdris/ocio). */
  sub?: string;
  /** Project slug for originals (`projects/{slug}/…`). */
  projectSlug?: string;
} {
  const slash = key.indexOf('/');
  const head = slash === -1 ? key : key.slice(0, slash);
  const rest = slash === -1 ? '' : key.slice(slash + 1);
  switch (head) {
    case 'projects': {
      const slug = rest.split('/')[0] ?? '';
      return { category: 'originals', projectSlug: slug || undefined };
    }
    case 'derived': {
      // derived/{mediaId}/<file...> -> subtype from the file name
      const afterId = rest.slice(rest.indexOf('/') + 1);
      return { category: 'derived', sub: derivedSubtype(rest.includes('/') ? afterId : rest) };
    }
    case 'studio':
      return { category: 'studio', sub: rest.split('/')[0] || 'other' };
    case 'avatars':
      return { category: 'avatars' };
    case 'branding':
      return { category: 'branding' };
    case 'documents':
      return { category: 'documents' };
    case 'comments':
      return { category: 'comments' };
    case 'quarantine':
      return { category: 'quarantine' };
    default:
      return { category: 'other' };
  }
}

const add = (m: Record<string, StorageAgg>, k: string, size: number) => {
  const agg = (m[k] ??= { count: 0, bytes: 0 });
  agg.count += 1;
  agg.bytes += size;
};

/** Map accumulator: the aggregation, object by object. */
export interface StorageAccumulator {
  /** Counts one object then forgets it: nothing is retained beyond the call. */
  add(object: StorageObjectInfo): void;
  /** Returns the aggregated report (projects sorted from heaviest to lightest). */
  finish(): StorageReportData;
}

/**
 * Builds the accumulator. It exists because the report is now built **during** the bucket sweep: the
 * memory held is that of the aggregates (a few dozen entries), not that of the objects (hundreds of
 * thousands on a studio instance). The arithmetic is exactly the same as before: `aggregateObjects`
 * reuses it as is.
 */
export function createStorageAccumulator(): StorageAccumulator {
  const categories: Record<string, StorageAgg> = {};
  const derived: Record<string, StorageAgg> = {};
  const studio: Record<string, StorageAgg> = {};
  const byProject: Record<string, StorageAgg> = {};
  let totalObjects = 0;
  let totalBytes = 0;
  return {
    add(o: StorageObjectInfo): void {
      totalObjects += 1;
      totalBytes += o.size;
      const c = classifyKey(o.key);
      add(categories, c.category, o.size);
      if (c.category === 'derived') add(derived, c.sub ?? 'other', o.size);
      if (c.category === 'studio') add(studio, c.sub ?? 'other', o.size);
      if (c.category === 'originals' && c.projectSlug) add(byProject, c.projectSlug, o.size);
    },
    finish(): StorageReportData {
      const projects = Object.entries(byProject)
        .map(([slug, agg]) => ({ slug, objects: agg.count, bytes: agg.bytes }))
        .sort((a, b) => b.bytes - a.bytes);
      return { totalObjects, totalBytes, categories, derived, studio, projects };
    },
  };
}

/** Aggregates a list of objects (key + size) into a mapping report. */
export function aggregateObjects(objects: Iterable<StorageObjectInfo>): StorageReportData {
  const acc = createStorageAccumulator();
  for (const o of objects) acc.add(o);
  return acc.finish();
}

/**
 * Same aggregate, fed by the MinIO scan stream. This variant is the one used in production: the
 * `iterateObjects` generator is consumed as it goes, and no intermediate array is built.
 */
export async function aggregateObjectsStream(
  objects: AsyncIterable<StorageObjectInfo>,
): Promise<StorageReportData> {
  const acc = createStorageAccumulator();
  for await (const o of objects) acc.add(o);
  return acc.finish();
}

/** Usage of a project, cross-referenced with the studio's known projects. */
export interface StorageReportProject {
  slug: string;
  objects: number;
  bytes: number;
  projectId: number | null;
  name: string | null;
  deleted: boolean;
}

export interface StorageReport extends Omit<StorageReportData, 'projects'> {
  projects: StorageReportProject[];
  generatedAt: string;
}

/**
 * Effective scan: cross-references the bucket aggregate with the known projects (navigable id,
 * readable name; an orphan slug = purged project, reported as such).
 */
async function scanStorage(): Promise<StorageReport> {
  // The stream is aggregated as it goes: a studio's bucket is all the rushes and all their HLS segments.
  // Materializing it as a JS array cost ~200 bytes per object, i.e. hundreds of megabytes for a single
  // opening of the Storage screen.
  const report = await aggregateObjectsStream(storage.iterateObjects());
  const known = await prisma.project.findMany({
    select: { id: true, slug: true, name: true, deletedAt: true },
  });
  const bySlug = new Map(known.map((p) => [p.slug, p]));
  return {
    ...report,
    projects: report.projects.map((p) => {
      const match = bySlug.get(p.slug);
      return {
        ...p,
        projectId: match?.id ?? null,
        name: match?.name ?? null,
        deleted: match ? match.deletedAt != null : false,
      };
    }),
    generatedAt: new Date().toISOString(),
  };
}

/**
 * Validity of the memoized report. The scan walks the whole bucket: without memoization, an
 * administrator who finds the screen slow and presses F5 twice launches three concurrent sweeps. The
 * report carries `generatedAt`, shown at the top of the Storage screen: a value one minute old reads as
 * such, it does not pass itself off as a fresh measurement.
 */
export const STORAGE_REPORT_TTL_MS = 60_000;

let cachedReport: { at: number; report: StorageReport } | null = null;
let scanInFlight: Promise<StorageReport> | null = null;

/** Forgets the memoized report (tests, and any explicit invalidation to come). */
export function resetStorageReportCache(): void {
  cachedReport = null;
  scanInFlight = null;
}

/** Full report, memoized and non-reentrant. */
export async function storageReport(): Promise<StorageReport> {
  const cached = cachedReport;
  if (cached && Date.now() - cached.at < STORAGE_REPORT_TTL_MS) return cached.report;
  // Only one sweep at a time: concurrent calls share the same scan instead of each launching one. They
  // receive the same snapshot, so nothing is stale for them.
  scanInFlight ??= scanStorage()
    .then((report) => {
      cachedReport = { at: Date.now(), report };
      return report;
    })
    .finally(() => {
      scanInFlight = null;
    });
  return scanInFlight;
}
