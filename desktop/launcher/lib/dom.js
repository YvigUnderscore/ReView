/**
 * `h('button', { class: 'button', onClick }, 'Texte')` — de quoi bâtir quelques écrans sans
 * framework. Le texte passe toujours par `textContent` : rien de ce qu'un serveur renvoie
 * (nom de studio, message d'erreur) n'est interprété comme du HTML.
 */
export function h(tag, props = {}, ...children) {
  const el = document.createElement(tag);
  for (const [key, value] of Object.entries(props)) {
    if (value === undefined || value === null || value === false) continue;
    if (key === 'class') el.className = value;
    else if (key.startsWith('on') && typeof value === 'function') {
      el.addEventListener(key.slice(2).toLowerCase(), value);
    } else el.setAttribute(key, value === true ? '' : String(value));
  }
  for (const child of children.flat()) {
    if (child === null || child === undefined || child === false) continue;
    el.append(child instanceof Node ? child : document.createTextNode(String(child)));
  }
  return el;
}
