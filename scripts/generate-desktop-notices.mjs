/**
 * Notices tierces de l'application desktop (`desktop/launcher/legal/THIRD-PARTY-NOTICES.txt`).
 *
 * Le binaire Tauri embarque quelque 400 crates Rust compilées statiquement, plus la police
 * Inter du lanceur. Les licences MIT, BSD, Apache, ISC… exigent que leur texte accompagne
 * le binaire distribué : ce fichier part dans l'installeur et s'affiche depuis le lanceur.
 * C'est le pendant, côté Rust, de `generate-notices.mjs` — même liste blanche, même refus
 * d'une licence inconnue.
 *
 *   node scripts/generate-desktop-notices.mjs          # régénère
 *   node scripts/generate-desktop-notices.mjs --check  # échoue si le fichier a vieilli
 *
 * `cargo` est requis (lecture du graphe par `cargo metadata`) : la vérification tourne
 * donc dans le workflow Desktop, pas dans `validate.sh`.
 */

import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { isAllowedLicense } from './generate-notices.mjs';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const OUTPUT = 'desktop/launcher/legal/THIRD-PARTY-NOTICES.txt';
const MANIFEST = 'desktop/src-tauri/Cargo.toml';

/** Composants distribués qui ne sont pas des crates. */
export const EXTRA_COMPONENTS = [
  {
    name: 'Inter (font)',
    version: '4 — @fontsource-variable/inter 5.2.8',
    license: 'OFL-1.1',
    repository: 'https://github.com/rsms/inter',
    licenseFiles: ['desktop/launcher/fonts/LICENSE-Inter.txt'],
  },
];

const LICENSE_FILE = /^(licen[cs]e|copying|notice|unlicense)([-._].*)?$/i;

/**
 * Marque d'ordre UTF-8 en tête du fichier : le protocole de Tauri sert un `.txt` sans
 * `charset`, et WebView2 le décode alors en Windows-1252 (« â€” » au lieu de « — »). La
 * marque fait foi pour le webview comme pour le Bloc-notes, avec la copie installée.
 */
const BOM = '﻿';

/** `MIT/Apache-2.0` (ancienne syntaxe Cargo) → `MIT OR Apache-2.0`. */
export function normalizeCargoLicense(expression) {
  if (!expression) return null;
  return expression
    .split('/')
    .map((part) => part.trim())
    .join(' OR ');
}

/**
 * Crates réellement liées au binaire : fermeture des dépendances « normales » depuis la
 * racine, toutes plateformes confondues (un seul fichier sert les trois installeurs).
 * Les dépendances de développement (tests) ne partent pas chez l'utilisateur.
 */
export function shippedPackages(metadata) {
  const nodes = new Map(metadata.resolve.nodes.map((n) => [n.id, n]));
  const root = metadata.resolve.root;
  const seen = new Set();
  const stack = [root];
  while (stack.length) {
    const id = stack.pop();
    if (seen.has(id)) continue;
    seen.add(id);
    for (const dep of nodes.get(id)?.deps ?? []) {
      const normal = dep.dep_kinds.some((k) => k.kind === null);
      if (normal) stack.push(dep.pkg);
    }
  }
  seen.delete(root);
  return metadata.packages
    .filter((p) => seen.has(p.id))
    .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

/** Fichiers de licence livrés avec une crate, dans un ordre stable. */
export function licenseFilesIn(names) {
  return names.filter((n) => LICENSE_FILE.test(n)).sort();
}

function readLicenseTexts(pkg) {
  const dir = path.dirname(pkg.manifest_path);
  let names;
  try {
    names = readdirSync(dir);
  } catch {
    return [];
  }
  return licenseFilesIn(names).map((n) => readFileSync(path.join(dir, n), 'utf8'));
}

/** Rend le fichier : inventaire, puis chaque texte de licence une seule fois. */
export function renderDesktopNotices(entries) {
  const groups = new Map();
  for (const e of entries) {
    const text = e.texts.map((t) => t.replace(/\r\n/g, '\n').trim()).join('\n\n---\n\n');
    const key = text ? createHash('sha256').update(text).digest('hex') : `none:${e.license}`;
    if (!groups.has(key)) groups.set(key, { text, license: e.license, members: [] });
    groups.get(key).members.push(`${e.name} ${e.version}`);
  }
  const lines = [
    'ReView Desktop — third-party notices',
    '',
    'ReView Desktop is free software under the GNU Affero General Public License v3.0 or later',
    '(see LICENSE.txt). It includes the third-party components listed below, each under its own',
    'license. This file is generated by scripts/generate-desktop-notices.mjs — do not edit it.',
    '',
    `Components (${entries.length})`,
    '',
    ...entries.map(
      (e) => `- ${e.name} ${e.version} — ${e.license}${e.repository ? ` — ${e.repository}` : ''}`,
    ),
    '',
  ];
  for (const g of groups.values()) {
    lines.push('='.repeat(80), '', `Used by: ${g.members.join(', ')}`, '');
    lines.push(
      g.text ||
        `No license file is shipped in these packages. They are distributed under ${g.license}; ` +
          'the standard text is published at https://spdx.org/licenses/.',
      '',
    );
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

function collect() {
  const raw = execFileSync(
    'cargo',
    ['metadata', '--format-version', '1', '--locked', '--manifest-path', MANIFEST],
    {
      cwd: repoRoot,
      encoding: 'utf8',
      maxBuffer: 64 * 1024 * 1024,
    },
  );
  const crates = shippedPackages(JSON.parse(raw)).map((p) => ({
    name: p.name,
    version: p.version,
    license: normalizeCargoLicense(p.license) ?? 'UNKNOWN',
    repository: p.repository ?? null,
    texts: readLicenseTexts(p),
  }));
  const extras = EXTRA_COMPONENTS.map((c) => ({
    ...c,
    texts: c.licenseFiles.map((f) => readFileSync(path.join(repoRoot, f), 'utf8')),
  }));
  return [...crates, ...extras];
}

function main() {
  const entries = collect();
  const refused = entries.filter((e) => !isAllowedLicense(e.license));
  if (refused.length) {
    console.error('Licences hors liste blanche (scripts/generate-notices.mjs, ALLOWED_LICENSES) :');
    for (const e of refused) console.error(`  ${e.name} ${e.version} — ${e.license}`);
    process.exit(1);
  }
  const content = renderDesktopNotices(entries);
  const target = path.join(repoRoot, OUTPUT);
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      const raw = readFileSync(target, 'utf8').replace(/\r\n/g, '\n');
      // Sans la marque, le fichier s'affiche mal : il compte comme périmé.
      current = raw.startsWith(BOM) ? raw.slice(BOM.length) : '';
    } catch {
      /* absent : traité comme périmé */
    }
    if (current !== content) {
      console.error(`${OUTPUT} est périmé — lancer : node scripts/generate-desktop-notices.mjs`);
      process.exit(1);
    }
    console.log(`✓ ${OUTPUT} à jour (${entries.length} composants)`);
    return;
  }
  writeFileSync(target, BOM + content);
  console.log(`${OUTPUT} écrit (${entries.length} composants, ${Math.round(content.length / 1024)} Kio)`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
